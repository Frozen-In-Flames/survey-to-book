def build_pack() -> dict:
    return {
        "genre": "memoir",
        "version": "1.0.0",
        "framework": FRAMEWORK,
        "chapters": CHAPTERS,
        "questions": QUESTIONS,
    }


def main() -> int:
    pack = build_pack()
    out = ROOT / "packs" / "memoir.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8") as fh:
        json.dump(pack, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    print(f"wrote {out}: {len(QUESTIONS)} questions, "
          f"{len(CHAPTERS)} chapters, {len(DEVICES)} devices")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

